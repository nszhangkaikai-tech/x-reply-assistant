const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require('node:path').join(__dirname, '../extension/content.js'), 'utf8');
const make = (id) => ({ id, text: id, querySelector: () => ({ innerText: id }), closest: () => null });
const rows = ['ancestor', 'root', 'sibling', 'target'].map(make);
const context = { capturedReplyThread: null, location: { pathname: '/user/status/123', href: 'https://x.com/user/status/123' }, document: { querySelector: selector => selector === 'main' ? { querySelectorAll: () => rows } : null }, readThreadMessage: row => row && ({ id: row.id === 'root' ? '123' : row.id, text: row.text, author: '@user' }) };
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('function readTargetThread('), source.indexOf('function readThreadMessage(')), context);
assert.deepEqual(Array.from(context.readTargetThread(rows[3]).contextMessages, m => m.text), ['ancestor', 'root']);
assert.deepEqual(Array.from(context.readTargetThread(rows[1]).contextMessages, m => m.text), ['ancestor']);
const modalTarget = make('target');
assert.deepEqual(Array.from(context.readTargetThread(modalTarget).contextMessages, m => m.text), ['ancestor', 'root']);
context.location.pathname = '/home';
assert.equal(context.readTargetThread(rows[3]).contextMessages.length, 0);
context.capturedReplyThread = { targetId: 'target', target: 'target', contextMessages: [{text:'root'}] };
const originalQuery = context.document.querySelector;
context.document.querySelector = selector => selector === '[role="dialog"]' ? {} : originalQuery(selector);
assert.equal(context.readTargetThread(rows[3]).contextMessages[0].text, 'root');
console.log('PASS: root, comment, modal, unrelated feed isolation');
